document.addEventListener('DOMContentLoaded', () => {
  // DOM Elements
  const shortenForm = document.getElementById('shorten-form');
  const longUrlInput = document.getElementById('long-url');
  const toggleOptionsBtn = document.getElementById('toggle-options');
  const toggleChevron = document.getElementById('toggle-chevron');
  const optionsContainer = document.getElementById('options-container');
  const customAliasInput = document.getElementById('custom-alias');
  const submitBtn = document.getElementById('submit-btn');
  const btnSpinner = document.getElementById('btn-spinner');
  
  // Success Card Elements
  const successCard = document.getElementById('success-card');
  const shortenedUrlDisplay = document.getElementById('shortened-url-display');
  const btnCopyResult = document.getElementById('btn-copy-result');
  const qrcodeContainer = document.getElementById('qrcode');
  const btnDownloadQr = document.getElementById('btn-download-qr');
  const successClicks = document.getElementById('success-clicks');
  const successCode = document.getElementById('success-code');
  const btnVisitLink = document.getElementById('btn-visit-link');
  
  // Dashboard Elements
  const linksTbody = document.getElementById('links-tbody');
  const dashboardSearch = document.getElementById('dashboard-search');
  const btnRefresh = document.getElementById('btn-refresh');
  const toastContainer = document.getElementById('toast-container');

  // Set domain prefix display based on current host
  const domainPrefix = document.getElementById('domain-prefix');
  domainPrefix.textContent = `${window.location.host}/`;

  let qrCodeInstance = null;
  let allLinks = [];

  // Toggle Advanced Options
  toggleOptionsBtn.addEventListener('click', () => {
    const isHidden = optionsContainer.classList.contains('hidden');
    if (isHidden) {
      optionsContainer.classList.remove('hidden');
      toggleChevron.classList.add('rotate');
    } else {
      optionsContainer.classList.add('hidden');
      toggleChevron.classList.remove('rotate');
      customAliasInput.value = ''; // Reset custom alias when closing
    }
  });

  // Handle Form Submission
  shortenForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    
    const longUrl = longUrlInput.value.strip ? longUrlInput.value.strip() : longUrlInput.value.trim();
    const customAlias = customAliasInput.value.strip ? customAliasInput.value.strip() : customAliasInput.value.trim();
    
    // Set loading state
    submitBtn.disabled = true;
    btnSpinner.classList.remove('hidden');

    try {
      const response = await fetch('/api/shorten', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ url: longUrl, alias: customAlias })
      });
      
      const result = await response.json();
      
      if (!response.ok) {
        throw new Error(result.error || 'Failed to shorten URL');
      }

      // Success workflow
      showToast('URL shortened successfully!', 'success');
      
      // Update result fields
      shortenedUrlDisplay.value = result.short_url;
      successClicks.textContent = '0';
      successCode.textContent = result.short_code;
      btnVisitLink.href = result.short_url;
      
      // Generate QR Code
      generateQRCode(result.short_url);

      // Reveal success card
      successCard.classList.remove('hidden');
      successCard.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
      
      // Reset form input
      longUrlInput.value = '';
      customAliasInput.value = '';
      if (!optionsContainer.classList.contains('hidden')) {
        optionsContainer.classList.add('hidden');
        toggleChevron.classList.remove('rotate');
      }

      // Refresh links in dashboard
      fetchLinks();

    } catch (err) {
      showToast(err.message, 'danger');
    } finally {
      // Restore button state
      submitBtn.disabled = false;
      btnSpinner.classList.add('hidden');
    }
  });

  // Generate QR Code
  function generateQRCode(text) {
    // Clear previous QR code
    qrcodeContainer.innerHTML = '';
    
    // Standard size 128x128
    qrCodeInstance = new QRCode(qrcodeContainer, {
      text: text,
      width: 128,
      height: 128,
      colorDark: '#060814',
      colorLight: '#ffffff',
      correctLevel: QRCode.CorrectLevel.H
    });
  }

  // Download QR Code
  btnDownloadQr.addEventListener('click', () => {
    // Attempt to download canvas or image generated by qrcode.js
    const canvas = qrcodeContainer.querySelector('canvas');
    const img = qrcodeContainer.querySelector('img');
    let dataUrl = '';

    if (canvas) {
      dataUrl = canvas.toDataURL('image/png');
    } else if (img && img.src) {
      dataUrl = img.src;
    }

    if (dataUrl) {
      const link = document.createElement('a');
      link.href = dataUrl;
      link.download = `trims-${successCode.textContent || 'qrcode'}.png`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      showToast('QR Code download started.', 'success');
    } else {
      showToast('Could not extract QR Code image.', 'danger');
    }
  });

  // Copy Short URL from Success Card
  btnCopyResult.addEventListener('click', () => {
    copyToClipboard(shortenedUrlDisplay.value);
    
    // Temporary change button state
    const icon = btnCopyResult.querySelector('i');
    icon.className = 'fa-solid fa-check';
    btnCopyResult.style.color = '#10b981';
    
    setTimeout(() => {
      icon.className = 'fa-regular fa-copy';
      btnCopyResult.style.color = '';
    }, 2000);
  });

  // Fetch Links and Populate Dashboard
  async function fetchLinks() {
    try {
      const response = await fetch('/api/links');
      if (!response.ok) throw new Error('Failed to fetch dashboard links');
      
      allLinks = await response.json();
      renderLinksTable(allLinks);
    } catch (err) {
      showToast(err.message, 'danger');
    }
  }

  // Render Table rows
  function renderLinksTable(links) {
    if (!links || links.length === 0) {
      linksTbody.innerHTML = `
        <tr class="empty-state">
          <td colspan="5">
            <div class="empty-state-content">
              <i class="fa-solid fa-link-slash"></i>
              <p>No links shortened yet. Paste a link above to get started!</p>
            </div>
          </td>
        </tr>
      `;
      return;
    }

    linksTbody.innerHTML = '';
    links.forEach(link => {
      const tr = document.createElement('tr');
      
      // Formatting date
      const date = new Date(link.created_at);
      const formattedDate = date.toLocaleDateString(undefined, { 
        month: 'short', 
        day: 'numeric', 
        year: 'numeric' 
      });

      tr.innerHTML = `
        <td>
          <div class="cell-long-url" title="${escapeHtml(link.original_url)}">
            ${escapeHtml(link.original_url)}
          </div>
        </td>
        <td>
          <a href="${link.short_url}" target="_blank" class="cell-short-url">
            ${escapeHtml(link.short_code)}
          </a>
        </td>
        <td>${link.clicks}</td>
        <td><span class="cell-date">${formattedDate}</span></td>
        <td>
          <div class="cell-actions">
            <button class="action-btn btn-copy-row" data-url="${link.short_url}" title="Copy short link">
              <i class="fa-regular fa-copy"></i>
            </button>
            <a href="${link.short_url}" target="_blank" class="action-btn" title="Open link">
              <i class="fa-solid fa-external-link-alt"></i>
            </a>
            <button class="action-btn btn-delete" data-code="${link.short_code}" title="Delete link">
              <i class="fa-regular fa-trash-can"></i>
            </button>
          </div>
        </td>
      `;
      linksTbody.appendChild(tr);
    });

    // Wire up dynamic click listeners for actions
    attachRowEventListeners();
  }

  // Attach event listeners for copy/delete buttons inside table
  function attachRowEventListeners() {
    // Copy Row
    linksTbody.querySelectorAll('.btn-copy-row').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const url = btn.getAttribute('data-url');
        copyToClipboard(url);
        
        const icon = btn.querySelector('i');
        icon.className = 'fa-solid fa-check';
        btn.style.color = '#10b981';
        setTimeout(() => {
          icon.className = 'fa-regular fa-copy';
          btn.style.color = '';
        }, 1500);
      });
    });

    // Delete Row
    linksTbody.querySelectorAll('.btn-delete').forEach(btn => {
      btn.addEventListener('click', async (e) => {
        const code = btn.getAttribute('data-code');
        if (confirm(`Are you sure you want to delete the shortened link /${code}?`)) {
          try {
            const response = await fetch(`/api/links/${code}`, { method: 'DELETE' });
            const result = await response.json();
            
            if (!response.ok) throw new Error(result.error || 'Failed to delete link');
            
            showToast('Link deleted successfully.', 'success');
            
            // Check if current success card details are for the deleted link, hide if so
            if (successCode.textContent === code) {
              successCard.classList.add('hidden');
            }

            fetchLinks();
          } catch (err) {
            showToast(err.message, 'danger');
          }
        }
      });
    });
  }

  // Copy helper
  function copyToClipboard(text) {
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text)
        .then(() => showToast('Link copied to clipboard!', 'success'))
        .catch(() => fallbackCopy(text));
    } else {
      fallbackCopy(text);
    }
  }

  function fallbackCopy(text) {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed'; // Avoid scrolling to bottom
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    try {
      document.execCommand('copy');
      showToast('Link copied to clipboard!', 'success');
    } catch (err) {
      showToast('Failed to copy link.', 'danger');
    }
    document.body.removeChild(textArea);
  }

  // Toast Notifications
  function showToast(message, type = 'info') {
    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    
    let iconClass = 'fa-circle-info';
    if (type === 'success') iconClass = 'fa-circle-check';
    if (type === 'danger') iconClass = 'fa-circle-exclamation';

    toast.innerHTML = `
      <i class="fa-solid ${iconClass}"></i>
      <span>${escapeHtml(message)}</span>
    `;

    toastContainer.appendChild(toast);

    // Fade out and remove
    setTimeout(() => {
      toast.classList.add('toast-fade-out');
      toast.addEventListener('transitionend', () => {
        toast.remove();
      });
    }, 3500);
  }

  // Search Filter
  dashboardSearch.addEventListener('input', (e) => {
    const query = e.target.value.toLowerCase().trim();
    if (!query) {
      renderLinksTable(allLinks);
      return;
    }

    const filtered = allLinks.filter(link => {
      return link.original_url.toLowerCase().includes(query) || 
             link.short_code.toLowerCase().includes(query);
    });
    
    renderLinksTable(filtered);
  });

  // Refresh Manual
  btnRefresh.addEventListener('click', () => {
    fetchLinks();
    showToast('Dashboard stats updated.', 'success');
  });

  // Escape HTML strings for security
  function escapeHtml(str) {
    if (!str) return '';
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  // Check URL parameters for redirect errors
  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.get('error') === 'not_found') {
    showToast('The requested short link does not exist or has expired.', 'danger');
    // Clean URL query parameters without reloading
    window.history.replaceState({}, document.title, window.location.pathname);
  }

  // Initial dashboard load
  fetchLinks();
});
